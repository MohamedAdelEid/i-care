const writeLocale = (locale, data) => {
  const dir = path.join(root, locale)
  fs.mkdirSync(dir, { recursive: true })
  for (const [ns, content] of Object.entries(data)) {
    fs.writeFileSync(path.join(dir, `${ns}.ts`), `export const ${ns} = ${JSON.stringify(content, null, 2)} as const\n`)
  }
  const imports = Object.keys(data).map((ns) => `import { ${ns} } from './${ns}'`).join('\n')
  const exports = Object.keys(data)
    .map((ns) => `  ${ns},`)
    .join('\n')
  fs.writeFileSync(
    path.join(dir, 'index.ts'),
    `${imports}\n\nimport type { Namespace } from '@/infrastructure/libs/i18n/namespaces'\n\nexport const ${locale}: Partial<Record<Namespace, Record<string, string>>> = {\n${exports}\n}\n`,
  )
}

writeLocale('en', en)
writeLocale('ar', ar)
